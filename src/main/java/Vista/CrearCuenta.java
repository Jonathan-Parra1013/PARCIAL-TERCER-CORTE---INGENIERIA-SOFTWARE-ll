    private void BotonCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonCrearActionPerformed
        limpiarMarcas();
        String clave = DatoPassword.getText();
        try {
            // Esta pantalla no tiene campo "confirmar contraseña" ni selector de rol:
            // se usa la misma clave como confirmación y la cuenta se crea como CLIENTE.
            usuarioService.registrar(DatoUsuario.getText(), DatoCorreo.getText(),
                    clave, clave, LogicaNegocio.UsuarioService.ROL_CLIENTE);
            javax.swing.JOptionPane.showMessageDialog(this, "Cuenta creada. Ya puedes iniciar sesión.");
            login.setCorreo(DatoCorreo.getText().trim().toLowerCase());
            dispose();
        } catch (LogicaNegocio.UsuarioException ex) {
            marcarCampo(ex.getCampo());
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Tienda online",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_BotonCrearActionPerformed

